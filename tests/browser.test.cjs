const {test} = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const {createService} = require('../service.cjs');

test('browser session is single-use, expires, hides pairing token, and survives page refresh',async t=>{
  const dir = fs.mkdtempSync(path.join(os.tmpdir(),'kanshan-browser-'));
  let opened = 0;
  const service = createService({dir,encrypt:s=>Buffer.from(s),decrypt:b=>b.toString(),openExtension:async()=>opened++});
  await new Promise(r=>service.server.listen(0,'127.0.0.1',r));
  t.after(()=>{service.dispose();service.server.close();fs.rmSync(dir,{recursive:true,force:true});});
  const launch = new URL(service.launchUrl());
  const origin = launch.origin;
  const code = new URLSearchParams(launch.hash.slice(1)).get('launch');
  const home = await fetch(origin);
  const html = await home.text();
  assert.ok(html.includes('live.js'));
  assert.ok(!html.includes(service.token));
  assert.ok(home.headers.get('content-security-policy').includes("frame-ancestors 'none'"));
  const submit = (value,source=origin) => fetch(origin+'/api/session',{method:'POST',headers:{Origin:source,'Content-Type':'application/json'},body:JSON.stringify({code:value})});
  assert.equal((await submit(code,'https://evil.example')).status,403);
  const session = await submit(code);
  assert.equal(session.status,200);
  const setCookie = session.headers.get('set-cookie');
  assert.ok(setCookie.includes('HttpOnly; SameSite=Strict'));
  const cookie = setCookie.split(';')[0];
  assert.equal((await submit(code)).status,401);
  assert.equal((await submit('invalid')).status,401);
  assert.equal((await fetch(origin+'/api/state')).status,401);
  const state = await fetch(origin+'/api/state',{headers:{Cookie:cookie}});
  assert.equal(state.status,200);
  assert.ok(!JSON.stringify(await state.json()).includes(service.token));
  const revision = await (await fetch(origin+'/api/revision',{headers:{Cookie:cookie}})).json();
  const body = JSON.stringify({title:'浏览器里创建的问题'});
  const headers = {Cookie:cookie,Origin:origin,'Content-Type':'application/json'};
  assert.equal((await fetch(origin+'/api/problems',{method:'POST',headers:{...headers,Origin:'https://evil.example'},body})).status,403);
  assert.equal((await fetch(origin+'/api/problems',{method:'POST',headers:{Cookie:cookie},body})).status,403);
  assert.equal((await fetch(origin+'/api/problems',{method:'POST',headers,body})).status,200);
  const unicodeBody=Buffer.from(JSON.stringify({title:'中文批注需要完整保存'}));
  const split=unicodeBody.indexOf(Buffer.from('中'))+1;
  const unicodeStatus=await new Promise((resolve,reject)=>{
    const req=http.request(origin+'/api/problems',{method:'POST',headers:{...headers,'Content-Length':unicodeBody.length}},res=>{res.resume();resolve(res.statusCode);});
    req.on('error',reject);req.write(unicodeBody.subarray(0,split));
    setTimeout(()=>req.end(unicodeBody.subarray(split)),10);
  });
  assert.equal(unicodeStatus,200);
  assert.equal(service.state().problems[0].title,'中文批注需要完整保存');
  const updated = await (await fetch(origin+'/api/revision',{headers})).json();
  assert.ok(updated.revision>revision.revision);
  assert.equal((await fetch(origin+'/api/extension',{method:'POST',headers,body:'{}'})).status,200);
  assert.equal(opened,1);
  const pair = await (await fetch(origin+'/api/connection',{headers})).json();
  assert.equal(pair.token,service.token);
  assert.equal((await fetch(origin+'/api/state',{headers:{Authorization:'Bearer '+service.token,Origin:'chrome-extension://'+'a'.repeat(32)}})).status,200);
  for (const name of ['library.json','credentials.bin','service.cjs','%2e%2e/package.json']) assert.equal((await fetch(origin+'/'+name)).status,404);
  const hostile = await new Promise((resolve,reject)=>{http.get(origin+'/api/state',{headers:{Host:'evil.example',Cookie:cookie}},res=>{res.resume();resolve(res.statusCode);}).on('error',reject);});
  assert.equal(hostile,403);
  const expiredCode = new URLSearchParams(new URL(service.launchUrl()).hash.slice(1)).get('launch');
  const currentTime = Date.now();
  t.mock.method(Date,'now',()=>currentTime+61000);
  assert.equal((await submit(expiredCode)).status,401);
  service.dispose();
  assert.equal((await fetch(origin+'/api/state',{headers})).status,401);
});
